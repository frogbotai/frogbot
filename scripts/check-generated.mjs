#!/usr/bin/env node
// check: full-only
// `pnpm check generated [--write]` regenerates every tracked `importMap.js`, `frogbot-types.ts`
// and `piece-types.ts` with a pinned environment and prints `stale: <path>` for each one that
// differs from the committed file. `--write` regenerates the stale files in place. Needs built
// packages.
import { spawn, spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { availableParallelism, tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { generateEnv, readJSON, ROOT } from './lib/workspace.mjs';

const FROGBOT_BIN = path.join(ROOT, 'packages', 'frogbot', 'bin.js');

const FROGBOT_DIST = path.join(ROOT, 'packages', 'frogbot', 'dist', 'bin', 'index.js');

const IMPORT_MAP_SCRIPT = path.join(ROOT, 'scripts', 'lib', 'generate-import-map.mjs');

const CONFIG_NAMES = ['config.ts', 'frogbot.config.ts'];

const TYPES_BANNER = 'This file was automatically generated by FrogBot.';

const PIECE_COMMAND = 'frogbot generate:piece-types ';

const PIECE_STALE = 'Piece types are stale';

const CHILD_TIMEOUT_MS = 120_000;

const USAGE = 'usage: pnpm check generated [--write]';

const KINDS = {
  'importMap.js': 'importMap',
  'frogbot-types.ts': 'types',
  'piece-types.ts': 'pieceTypes',
};

function projectDir(file, projects) {
  for (let dir = path.posix.dirname(file); dir !== '.'; dir = path.posix.dirname(dir)) {
    if (projects.has(dir)) return dir;
  }

  return undefined;
}

export function generatedTargets({ files, projects, exists, read }) {
  return files.flatMap((file) => {
    const kind = KINDS[path.posix.basename(file)];
    const cwd = kind && projectDir(file, projects);

    if (!cwd) return [];

    if (kind !== 'types') return [{ kind, file, cwd }];

    if (!read(file).includes(TYPES_BANNER)) return [];

    const dir = path.posix.dirname(file);
    const config = CONFIG_NAMES.map((name) => path.posix.join(dir, name)).find(exists);

    return [{ kind, file, config }];
  });
}

export function pieceTypesArgs(script, file) {
  if (!script?.startsWith(PIECE_COMMAND)) return undefined;

  const args = ['generate:piece-types', ...script.slice(PIECE_COMMAND.length).trim().split(/\s+/)];
  const output = args[args.indexOf('--output') + 1];

  return output && path.posix.basename(file) === path.posix.basename(output) ? args : undefined;
}

export function summarize(results) {
  const sorted = [...results].sort((a, b) => a.file.localeCompare(b.file));

  const lines = sorted.flatMap(({ file, status, message }) => {
    if (status === 'stale') return [`stale: ${file}`];

    if (status === 'written') return [`wrote: ${file}`];

    if (status === 'error') return [`error: ${file}: ${message}`];

    return [];
  });

  const ok = sorted.every(({ status }) => status === 'fresh' || status === 'written');

  return { ok, lines: ok ? [...lines, `generated: OK (${results.length} files)`] : lines };
}

function lines(text) {
  return text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);
}

function errorLine(output) {
  const found = lines(output);

  return (
    found.find((line) => /^(\w*Error\b|\[frogbot\])/.test(line)) ?? found.at(-1) ?? 'no output'
  );
}

function node(args, { cwd, env }) {
  return new Promise((resolve) => {
    const child = spawn(process.execPath, args, {
      cwd,
      env,
      stdio: ['ignore', 'pipe', 'pipe'],
      timeout: CHILD_TIMEOUT_MS,
    });

    let stdout = '';
    let output = '';

    child.stdout.on('data', (chunk) => {
      stdout += chunk;
      output += chunk;
    });

    child.stderr.on('data', (chunk) => (output += chunk));
    child.on('error', (error) => resolve({ code: null, stdout, output: error.message }));
    child.on('close', (code) => resolve({ code, stdout, output }));
  });
}

async function checkTypes({ file, config }, { write, tmp, index }) {
  if (!config) return { status: 'error', message: `no ${CONFIG_NAMES.join(' or ')} next to it` };

  const output = path.join(tmp, `${index}.ts`);

  const result = await node([FROGBOT_BIN, 'generate:types'], {
    cwd: tmp,
    env: generateEnv({
      FROGBOT_CONFIG_PATH: path.join(ROOT, config),
      FROGBOT_TS_OUTPUT_PATH: output,
    }),
  });

  if (result.code !== 0) return { status: 'error', message: errorLine(result.output) };

  const tracked = path.join(ROOT, file);

  if (readFileSync(output, 'utf8') === readFileSync(tracked, 'utf8')) return { status: 'fresh' };

  if (!write) return { status: 'stale' };

  copyFileSync(output, tracked);

  return { status: 'written' };
}

async function checkImportMap({ cwd }, { write }) {
  const args = write ? [IMPORT_MAP_SCRIPT, '--write'] : [IMPORT_MAP_SCRIPT];
  const result = await node(args, { cwd: path.join(ROOT, cwd), env: generateEnv() });

  if (result.code !== 0) return { status: 'error', message: errorLine(result.output) };

  const { changed } = JSON.parse(lines(result.stdout).at(-1));

  if (!changed) return { status: 'fresh' };

  return { status: write ? 'written' : 'stale' };
}

async function checkPieceTypes({ file, cwd }, { write }) {
  const script = readJSON(path.join(ROOT, cwd, 'package.json')).scripts?.['generate:types'];
  const args = pieceTypesArgs(script, file);

  if (!args)
    return { status: 'error', message: `no "${PIECE_COMMAND.trim()}" generate:types script` };

  const result = await node([FROGBOT_BIN, ...args, ...(write ? [] : ['--check'])], {
    cwd: path.join(ROOT, cwd),
    env: generateEnv(),
  });

  if (result.code === 0) return { status: write && result.stdout.trim() ? 'written' : 'fresh' };

  if (!write && result.output.includes(PIECE_STALE)) return { status: 'stale' };

  return { status: 'error', message: errorLine(result.output) };
}

const CHECKS = { types: checkTypes, importMap: checkImportMap, pieceTypes: checkPieceTypes };

async function mapLimit(items, limit, work) {
  const results = [];
  let next = 0;

  const worker = async () => {
    while (next < items.length) {
      const index = next++;

      results[index] = await work(items[index], index);
    }
  };

  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));

  return results;
}

function trackedFiles() {
  const listed = spawnSync('git', ['ls-files', '-z'], { cwd: ROOT, encoding: 'utf8' });

  return listed.stdout.split('\0').filter(Boolean);
}

function workspaceProjects() {
  const listed = spawnSync('pnpm', ['ls', '-r', '--depth', '-1', '--json'], {
    cwd: ROOT,
    encoding: 'utf8',
  });

  return new Set(
    JSON.parse(listed.stdout).map(({ path: dir }) =>
      path.relative(ROOT, dir).split(path.sep).join('/'),
    ),
  );
}

async function main() {
  const args = process.argv.slice(2);
  const unknown = args.find((arg) => arg !== '--write');

  if (unknown) {
    console.error(`generated: unknown argument "${unknown}". ${USAGE}`);
    process.exit(2);
  }

  if (!existsSync(FROGBOT_DIST)) {
    console.error('generated: build the packages first (pnpm -r --filter "./packages/**" build)');
    process.exit(1);
  }

  const write = args.includes('--write');
  const targets = generatedTargets({
    files: trackedFiles(),
    projects: workspaceProjects(),
    exists: (file) => existsSync(path.join(ROOT, file)),
    read: (file) => readFileSync(path.join(ROOT, file), 'utf8'),
  });
  const tmp = mkdtempSync(path.join(tmpdir(), 'frogbot-check-generated-'));
  const limit = Math.max(1, Math.floor(availableParallelism() / 2));

  try {
    const results = await mapLimit(targets, limit, async (target, index) => ({
      file: target.file,
      ...(await CHECKS[target.kind](target, { write, tmp, index })),
    }));

    const { ok, lines } = summarize(results);

    console.log(lines.join('\n'));

    process.exitCode = ok ? 0 : 1;
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
