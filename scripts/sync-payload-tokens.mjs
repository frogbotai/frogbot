#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { ROOT } from './lib/workspace.mjs';

/** The admin panel's color tokens, copied for FrogBot UI pages outside the admin. Run after a Payload bump. */
export const OUTPUT = path.join(ROOT, 'packages/ui/src/payload-tokens.css');

const SOURCE = path.join(ROOT, 'packages/ui/node_modules/@payloadcms/ui');

const FILES = ['design-tokens.css', 'colors.css', 'elevations.css', 'utilities.css', 'theme.css'];

const THEME_NAMES = /^--stroke-width-/;

const ALIASES = /^--accessibility-|^--scrollbar-color$/;

const PAGE = ':where(html:not([data-fb-ui-page]))';

const LIGHT = ":where(:not(html)[data-theme='light'])";

const DARK = `:where(html:not([data-fb-ui-page])[data-theme='dark'], html:not([data-fb-ui-page]) [data-theme='dark'])`;

function blocks(css) {
  const body = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const result = [];

  for (const match of body.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selector = match[1]
      .trim()
      .replace(/^@layer payload-default\s*\{?/, '')
      .trim();

    const declarations = [...match[2].matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(
      ([, name, value]) => [name, value.replace(/\s+/g, ' ').trim()],
    );

    if (declarations.length) result.push({ declarations, selector });
  }

  return result;
}

export function readPayloadTokens(source = SOURCE) {
  const { version } = JSON.parse(readFileSync(path.join(source, 'package.json'), 'utf8'));
  const page = [];
  const dark = [];

  for (const file of FILES) {
    for (const { declarations, selector } of blocks(
      readFileSync(path.join(source, 'dist/css', file), 'utf8'),
    )) {
      if (selector === ':root') {
        page.push(
          ...declarations.filter(([name]) => file !== 'theme.css' || THEME_NAMES.test(name)),
        );
      } else if (
        selector.includes("[data-theme='dark']") &&
        !selector.includes('[data-enhanced-contrast]')
      ) {
        dark.push(...declarations);
      }
    }
  }

  const themed = new Set(dark.map(([name]) => name));
  const aliases = page.filter(([name]) => ALIASES.test(name));
  const light = [...page.filter(([name]) => themed.has(name)), ...aliases];

  return { dark: [...dark, ...aliases], light, page, version };
}

function block(selector, declarations) {
  return [
    `  ${selector} {`,
    ...declarations.map(([name, value]) => `    ${name}: ${value};`),
    '  }',
  ].join('\n');
}

export function renderPayloadTokens(tokens = readPayloadTokens()) {
  return `/*
 * Generated by scripts/sync-payload-tokens.mjs from the admin panel package, version ${tokens.version}. Do not edit.
 * The admin panel's color ramps and semantic tokens, for pages outside the admin. In the admin
 * the admin's own tokens apply; the light block only serves a light section inside a dark page.
 */
@layer theme.frogbot {
${block(PAGE, tokens.page)}

${block(LIGHT, tokens.light)}

${block(DARK, tokens.dark)}
}
`;
}

/** The file as written: `renderPayloadTokens()` formatted with the repo's Prettier config. */
export async function formatPayloadTokens(css = renderPayloadTokens()) {
  const prettier = await import('prettier');
  const options = await prettier.resolveConfig(OUTPUT);

  return prettier.format(css, { ...options, filepath: OUTPUT });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, await formatPayloadTokens());
  console.log(`wrote ${path.relative(ROOT, OUTPUT)}`);
}
