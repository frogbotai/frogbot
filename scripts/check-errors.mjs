#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import ts from 'typescript';

import { readJSON, ROOT } from './lib/workspace.mjs';

export const PAGE = path.join(ROOT, 'docs', 'errors.mdx');

const PACKAGES = path.join(ROOT, 'packages');

const SKIPPED_DIRS = new Set(['node_modules', 'dist', '.typetest-copy', '.next']);

const SOURCE_FILE = /\.tsx?$/;

const CATALOG_MARKER = /\bdefineErrors\(|\bErrorDefinition>/;

const DEFINES_ERRORS = /\bexport function defineErrors\b/;

const CORE = 'frogbot';

const USAGE = 'usage: pnpm check errors [--write]';

const HEADER = `---
title: Errors
description: Every error code FrogBot and its plugins send, with what to do about it.
---

{/* Generated by \`pnpm check errors --write\` from each package's \`defineErrors\` catalog. Don't edit by hand. */}

Every failure FrogBot sends over REST, MCP, the SDK and the CLI is a [Problem](/rest-api/overview#errors). Branch on its \`code\`, follow its \`hint\`, and retry only when \`retryable\` is \`true\`. Each \`type\` links to the code's row here.
`;

function propertyName(name) {
  if (ts.isIdentifier(name) || ts.isStringLiteral(name)) return name.text;

  return undefined;
}

function constantStrings(sourceFile) {
  const strings = new Map();

  for (const statement of sourceFile.statements) {
    if (!ts.isVariableStatement(statement)) continue;

    for (const declaration of statement.declarationList.declarations) {
      const { initializer, name } = declaration;

      if (ts.isIdentifier(name) && initializer && ts.isStringLiteralLike(initializer)) {
        strings.set(name.text, initializer.text);
      }
    }
  }

  return strings;
}

function literal(node, strings) {
  if (ts.isStringLiteralLike(node)) return node.text;
  if (ts.isNumericLiteral(node)) return Number(node.text);
  if (node.kind === ts.SyntaxKind.TrueKeyword) return true;
  if (node.kind === ts.SyntaxKind.FalseKeyword) return false;
  if (ts.isIdentifier(node)) return strings.get(node.text);

  return undefined;
}

function definitionOf(node, strings) {
  const values = {};

  for (const property of node.properties) {
    if (!ts.isPropertyAssignment(property)) continue;

    const key = propertyName(property.name);

    if (key) values[key] = literal(property.initializer, strings);
  }

  return typeof values.status === 'number' && 'title' in values ? values : undefined;
}

/** The error definitions a catalog source declares: every `'code': { status, title, … }` entry. */
export function catalogDefinitions({ file, source, packageName }) {
  const sourceFile = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
  const strings = constantStrings(sourceFile);
  const definitions = [];

  const visit = (node) => {
    if (
      ts.isPropertyAssignment(node) &&
      ts.isObjectLiteralExpression(node.initializer) &&
      propertyName(node.name)
    ) {
      const values = definitionOf(node.initializer, strings);

      if (values) {
        const { line } = sourceFile.getLineAndCharacterOfPosition(node.getStart());

        definitions.push({
          code: propertyName(node.name),
          status: values.status,
          title: values.title,
          hint: values.hint,
          retryable: values.retryable === true,
          package: packageName,
          file,
          line: line + 1,
        });

        return;
      }
    }

    ts.forEachChild(node, visit);
  };

  visit(sourceFile);

  return definitions;
}

/** The prefix a package's codes start with: none for core, else its short name and a dot. */
export function codePrefix(packageName) {
  if (packageName === CORE) return undefined;

  return `${packageName.replace(/^@[^/]+\//, '').replace(/^plugin-/, '')}.`;
}

function mentions(source, text) {
  return ["'", '"', '`'].some((quote) => source.includes(`${quote}${text}${quote}`));
}

function raised(sources, code) {
  if (sources.some((source) => mentions(source, code))) return true;

  const dot = code.indexOf('.');

  if (dot === -1) return false;

  const template = `\`${code.slice(0, dot + 1)}\${`;
  const reason = code.slice(dot + 1);

  return (
    sources.some((source) => source.includes(template)) &&
    sources.some((source) => mentions(source, reason))
  );
}

/** What is wrong with the catalogs: missing words, wrong prefixes, duplicates and unraised codes. */
export function catalogProblems({ definitions, sources }) {
  const problems = [];
  const seen = new Map();

  for (const definition of definitions) {
    const { code, file, line } = definition;
    const at = { file, line };
    const prefix = codePrefix(definition.package);

    if (!definition.title) problems.push({ ...at, message: `${code} has no title.` });
    if (!definition.hint) problems.push({ ...at, message: `${code} has no hint.` });

    if (prefix && !code.startsWith(prefix)) {
      problems.push({ ...at, message: `${code} must start with ${prefix}` });
    }

    if (seen.has(code)) {
      problems.push({ ...at, message: `${code} is also defined at ${seen.get(code)}.` });
    } else {
      seen.set(code, `${file}:${line}`);
    }

    if (!raised(sources, code)) {
      problems.push({ ...at, message: `${code} is never raised; remove it or throw it.` });
    }
  }

  return problems;
}

function cell(text = '') {
  return String(text).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

/** `docs/errors.mdx`: one table per package, one row per code, each row anchored by its code. */
export function errorsPage(definitions) {
  const byPackage = new Map();

  for (const definition of definitions) {
    byPackage.set(definition.package, [...(byPackage.get(definition.package) ?? []), definition]);
  }

  const order = [...byPackage.keys()].sort((a, b) =>
    a === CORE ? -1 : b === CORE ? 1 : a.localeCompare(b),
  );

  const sections = order.map((name) => {
    const rows = byPackage
      .get(name)
      .toSorted((a, b) => a.code.localeCompare(b.code))
      .map(
        ({ code, status, title, hint, retryable }) =>
          `| <code id="${code}">${code}</code> | ${status} | ${cell(title)} | ${cell(hint)} | ${retryable ? 'Yes' : 'No'} |`,
      );

    return [
      `## \`${name}\``,
      '',
      '| Code | Status | Title | What to do | Retry |',
      '| ---- | ------ | ----- | ---------- | ----- |',
      ...rows,
    ].join('\n');
  });

  return `${HEADER}\n${sections.join('\n\n')}\n`;
}

/** Every problem with the catalogs and the page, and the page they should produce. */
export function checkErrors({ definitions, sources, current }) {
  const page = errorsPage(definitions);
  const problems = catalogProblems({ definitions, sources });

  if (current !== page) {
    problems.push({
      file: path.relative(ROOT, PAGE),
      line: 1,
      message: 'is stale; run `pnpm check errors --write`.',
    });
  }

  return { page, problems };
}

function sourceFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (SKIPPED_DIRS.has(entry.name)) return [];

    const file = path.join(dir, entry.name);

    if (entry.isDirectory()) return sourceFiles(file);

    return SOURCE_FILE.test(entry.name) ? [file] : [];
  });
}

function packageNameOf(file) {
  for (let dir = path.dirname(file); dir.startsWith(PACKAGES); dir = path.dirname(dir)) {
    try {
      return readJSON(path.join(dir, 'package.json')).name;
    } catch {
      continue;
    }
  }

  return undefined;
}

/** Every package source file, read once, and the error definitions the catalogs among them declare. */
export function readCatalogs() {
  const files = sourceFiles(PACKAGES)
    .filter((file) => file.split(path.sep).includes('src'))
    .map((file) => ({ file: path.relative(ROOT, file), source: readFileSync(file, 'utf8') }));

  const catalogs = files.filter(
    ({ source }) => CATALOG_MARKER.test(source) && !DEFINES_ERRORS.test(source),
  );

  const definitions = catalogs.flatMap(({ file, source }) =>
    catalogDefinitions({ file, source, packageName: packageNameOf(path.join(ROOT, file)) }),
  );

  const catalogFiles = new Set(catalogs.map(({ file }) => file));
  const sources = files.filter(({ file }) => !catalogFiles.has(file)).map(({ source }) => source);

  return { definitions, sources };
}

function main() {
  const args = process.argv.slice(2);
  const write = args.includes('--write');

  if (args.some((arg) => arg !== '--write')) {
    console.error(USAGE);
    process.exit(2);
  }

  const { definitions, sources } = readCatalogs();
  let current = '';

  try {
    current = readFileSync(PAGE, 'utf8');
  } catch {
    current = '';
  }

  const { page, problems } = checkErrors({ definitions, sources, current });
  const fresh = problems.filter(({ message }) => !(write && message.startsWith('is stale')));

  if (write && current !== page) writeFileSync(PAGE, page);

  if (fresh.length > 0) {
    for (const { file, line, message } of fresh) console.error(`${file}:${line}  ${message}`);

    console.error(`\n[check-errors] FAIL - ${fresh.length} issue(s) found.`);
    process.exit(1);
  }

  console.log(`[check-errors] OK - ${definitions.length} codes documented in docs/errors.mdx.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
